"""Pure generators for smb.conf and /etc/exports.d content."""
from __future__ import annotations

import os
from typing import Dict, List

HEADER = "# Generated by Talon - manual changes will be overwritten.\n"


def _q(name: str) -> str:
    return f'"{name}"' if " " in name else name


def share_path(share: dict, volumes: Dict[str, dict]) -> str:
    vol = volumes[share["volume"]]
    return os.path.join(vol["mountpoint"], share["folder"])


def principals(share: dict) -> Dict[str, List[str]]:
    """Return {'ro': [...], 'rw': [...]} using Samba syntax (@group)."""
    ro, rw = [], []
    for u, acc in sorted(share.get("users", {}).items()):
        (rw if acc == "rw" else ro if acc == "ro" else []).append(u)
    for g, acc in sorted(share.get("groups", {}).items()):
        (rw if acc == "rw" else ro if acc == "ro" else []).append("@" + g)
    return {"ro": ro, "rw": rw}


def smb_conf(settings: dict, shares: Dict[str, dict], volumes: Dict[str, dict]) -> str:
    g = [
        "[global]",
        f"   workgroup = {settings.get('workgroup', 'WORKGROUP')}",
        f"   server string = {settings.get('server_string', 'Talon')}",
        "   server role = standalone server",
        "   security = user",
        "   passdb backend = tdbsam",
        "   map to guest = Bad User",
        "   guest account = nobody",
        f"   server min protocol = {settings.get('smb_min_protocol', 'SMB2_10')}",
        "   disable netbios = no",
        "   load printers = no",
        "   printing = bsd",
        "   printcap name = /dev/null",
        "   disable spoolss = yes",
        "   log file = /var/log/samba/log.%m",
        "   max log size = 1000",
        "   logging = file",
        "   unix extensions = no",
        "   ea support = yes",
    ]
    if settings.get("smb_macos_compat", True):
        g += [
            "   vfs objects = catia fruit streams_xattr",
            "   fruit:metadata = stream",
            "   fruit:model = MacSamba",
            "   fruit:posix_rename = yes",
            "   fruit:veto_appledouble = no",
            "   fruit:nfs_aces = no",
            "   fruit:wipe_intentionally_left_blank_rfork = yes",
            "   fruit:delete_empty_adfiles = yes",
        ]
    out = [HEADER] + g + [""]
    for name in sorted(shares):
        s = shares[name]
        if not s.get("smb", {}).get("enabled") or s["volume"] not in volumes:
            continue
        smb = s["smb"]
        p = principals(s)
        guest = s.get("guest", "none") == "ro"
        lines = [
            f"[{name}]",
            f"   path = {share_path(s, volumes)}",
        ]
        if s.get("description"):
            lines.append(f"   comment = {s['description']}")
        lines += [
            f"   browseable = {'yes' if smb.get('browseable', True) else 'no'}",
            "   read only = yes",
            f"   guest ok = {'yes' if guest else 'no'}",
        ]
        if not guest:
            allowed = p["ro"] + p["rw"]
            # an empty valid users list would allow everyone - deny instead
            lines.append(f"   valid users = {' '.join(map(_q, allowed)) if allowed else 'nobody'}")
            if not allowed:
                lines.append("   invalid users = root")
        if p["rw"]:
            lines.append(f"   write list = {' '.join(map(_q, p['rw']))}")
        lines += [
            "   force group = +nasusers",
            "   create mask = 0664",
            "   directory mask = 2775",
            "   inherit acls = yes",
        ]
        vfs = []
        if settings.get("smb_macos_compat", True):
            vfs += ["catia", "fruit", "streams_xattr"]
        if smb.get("recycle_bin"):
            vfs.append("recycle")
            lines += [
                "   recycle:repository = .recycle/%U",
                "   recycle:keeptree = yes",
                "   recycle:versions = yes",
                "   recycle:touch = yes",
                "   recycle:directory_mode = 0770",
            ]
        if smb.get("time_machine"):
            lines += ["   fruit:time machine = yes"]
        if vfs:
            lines.append(f"   vfs objects = {' '.join(vfs)}")
        out += lines + [""]
    return "\n".join(out)


def nfs_exports(shares: Dict[str, dict], volumes: Dict[str, dict], users_gid: int) -> str:
    out = [HEADER.rstrip()]
    for name in sorted(shares):
        s = shares[name]
        nfs = s.get("nfs", {})
        if not nfs.get("enabled") or s["volume"] not in volumes or not nfs.get("clients"):
            continue
        squash = nfs.get("squash", "all")
        opts_common = ["sync", "no_subtree_check"]
        if squash == "all":
            opts_common += ["all_squash", "anonuid=65534", f"anongid={users_gid}"]
        elif squash == "root":
            opts_common += ["root_squash"]
        else:
            opts_common += ["no_root_squash"]
        if nfs.get("insecure"):
            opts_common.append("insecure")
        clients = []
        for c in nfs["clients"]:
            access = "rw" if c.get("access") == "rw" else "ro"
            clients.append(f"{c['host']}({','.join([access] + opts_common)})")
        path = share_path(s, volumes)
        if any(ch.isspace() for ch in path):
            path = '"' + path + '"'
        out.append(f"{path} {' '.join(clients)}")
    return "\n".join(out) + "\n"
